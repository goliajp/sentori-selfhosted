import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { withLiveBrowsers } from './live-browser.mjs';
const results=[];
await withLiveBrowsers('self-hosted', async ({engine,context,page,origin,out,password,call})=>{
  await call('/auth/login',{email:'owner@example.test',password},'POST',200);
  await page.setViewportSize({width:320,height:900});
  await page.goto(origin+'/settings/instance');
  const health=page.getByTestId('instance-health');
  await health.getByRole('button',{name:'Check instance health',exact:true}).click();
  await health.getByText('Disaster recovery evidence · Unverified',{exact:true}).waitFor();
  assert.match(await health.innerText(),/Off-host copies/);
  await page.route('**/admin/api/instance/health',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'unavailable',code:'unavailable'})}),{times:1});
  await health.getByRole('button',{name:'Check instance health',exact:true}).click();
  await health.getByRole('alert').waitFor();
  assert.equal(await health.getByText('Disaster recovery evidence · Unverified',{exact:true}).count(),0);
  await health.getByRole('button',{name:'Check instance health',exact:true}).click();
  await health.getByText('Disaster recovery evidence · Unverified',{exact:true}).waitFor();
  await page.screenshot({path:`${out}/${engine}-health-320.png`,fullPage:true});
  await page.goto(origin+'/self-hosted?tab=backups');
  await page.getByRole('button',{name:'Create backup',exact:true}).waitFor();
  await page.getByRole('button',{name:'Create backup',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.waitFor();
  await page.screenshot({path:`${out}/${engine}-create-320.png`,fullPage:true});
  assert.equal(await dialog.getByRole('button',{name:'Create backup',exact:true}).isEnabled(),false);
  const keyDownload=page.waitForEvent('download');
  await dialog.getByRole('button',{name:'Download recovery key',exact:true}).click();
  const keyFile=await keyDownload;
  const key=readFileSync(await keyFile.path(),'utf8').trim();
  assert.match(key,/^[a-f0-9]{64}$/);
  await dialog.getByRole('checkbox').check();
  // The response disappears after a real commit. Retrying must use the same command.
  let committed;
  const route=async route=>{
    if(route.request().method()!=='POST')return route.continue();
    const response=await route.fetch();
    assert.equal(response.status(),200);
    committed=(await response.json()).operation.id;
    await route.abort('failed');
  };
  await page.route('**/admin/api/instance/operations',route);
  await dialog.getByRole('button',{name:'Create backup',exact:true}).click();
  await dialog.getByRole('button',{name:'Retry',exact:true}).waitFor();
  await page.unroute('**/admin/api/instance/operations',route);
  await dialog.getByRole('button',{name:'Retry',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  const row=page.locator(`[data-operation-id="${committed}"]`);
  await row.getByText('Verified',{exact:true}).waitFor({timeout:60000});
  const download=page.waitForEvent('download');
  await row.getByRole('link',{name:'Download archive',exact:true}).click();
  const archive=readFileSync(await (await download).path());
  const digest=createHash('sha256').update(archive).digest('hex');
  assert.ok((await row.textContent()).includes(digest));
  assert.equal(archive.includes(Buffer.from('owner@example.test')),false);
  assert.equal(archive.includes(Buffer.from(key)),false);
  const items=(await call('/admin/api/instance/operations')).items;
  assert.equal(items.filter(item=>item.id===committed).length,1);
  await page.reload();
  await page.locator(`[data-operation-id="${committed}"]`).getByText('Verified',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Upload and verify',exact:true}).click();
  const verifyDialog=page.getByRole('dialog');
  await verifyDialog.getByLabel('Encrypted backup file',{exact:true}).setInputFiles({name:'recovery.sentori',mimeType:'application/octet-stream',buffer:archive});
  await verifyDialog.getByLabel('Recovery key file',{exact:true}).setInputFiles({name:'recovery.key',mimeType:'text/plain',buffer:Buffer.from(key+'\n')});
  await page.screenshot({path:`${out}/${engine}-verify-320.png`,fullPage:true});
  const uploadedResponse=page.waitForResponse(response=>response.url().endsWith('/admin/api/instance/operations/verify')&&response.request().method()==='POST');
  await verifyDialog.getByRole('button',{name:'Verify archive',exact:true}).click();
  const uploaded=(await (await uploadedResponse).json()).operation.id;
  await verifyDialog.waitFor({state:'hidden'});
  await page.locator(`[data-operation-id="${uploaded}"]`).getByText('Verified',{exact:true}).waitFor({timeout:60000});
  assert.ok((await page.locator(`[data-operation-id="${uploaded}"]`).textContent()).includes(digest));
  await page.getByRole('button',{name:'Upload and verify',exact:true}).click();
  await verifyDialog.getByLabel('Encrypted backup file',{exact:true}).setInputFiles({name:'wrong-key.sentori',mimeType:'application/octet-stream',buffer:archive});
  await verifyDialog.getByLabel('Recovery key file',{exact:true}).setInputFiles({name:'wrong.key',mimeType:'text/plain',buffer:Buffer.from('a5'.repeat(32)+'\n')});
  const failedResponse=page.waitForResponse(response=>response.url().endsWith('/admin/api/instance/operations/verify')&&response.request().method()==='POST');
  await verifyDialog.getByRole('button',{name:'Verify archive',exact:true}).click();
  const rejected=(await (await failedResponse).json()).operation.id;
  await verifyDialog.waitFor({state:'hidden'});
  const failedRow=page.locator(`[data-operation-id="${rejected}"]`);
  await failedRow.getByText('Failed',{exact:true}).waitFor({timeout:60000});
  assert.ok((await failedRow.textContent()).includes('Verification failed. Check the recovery key'));
  assert.equal(await failedRow.getByRole('link',{name:'Download archive',exact:true}).count(),0);
  // Check actual content after API settlement, not just the loading skeleton.
  for(const locale of ['en','zh','ja'])for(const theme of ['light','dark'])for(const width of [320,390,768,1440,2560,3840])for(const tab of ['overview','setup','backups','activity']){
    await page.evaluate(({locale,theme})=>{localStorage.setItem('sentori_locale',locale);localStorage.setItem('sentori-theme',theme);},{locale,theme});
    await page.setViewportSize({width,height:900});
    await page.goto(origin+`/self-hosted?tab=${tab}`);
    await page.locator('.host-page [role=tablist]').waitFor();
    await page.waitForLoadState('networkidle');
    await page.evaluate(()=>document.fonts.ready);
    const overflow=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,lang:document.documentElement.lang,theme:document.documentElement.dataset.theme}));
    assert.equal(overflow.lang,locale); assert.equal(overflow.theme,theme);
    assert.ok(overflow.document<=overflow.viewport+1,JSON.stringify({engine,locale,theme,width,tab,overflow}));
    assert.equal(await page.locator('.host-page [role=alert]').count(),0);
    if(locale==='en'&&theme==='light'&&[320,1440].includes(width))await page.screenshot({path:`${out}/${engine}-${tab}-${width}.png`,fullPage:true});
    results.push({engine,locale,theme,width,tab});
  }
  await page.evaluate(()=>localStorage.setItem('sentori_locale','en'));
  await call('/auth/logout',{},'POST',200);
  await call('/auth/login',{email:'member@example.test',password},'POST',200);
  await page.goto(origin+'/self-hosted?tab=backups');
  await page.locator('.host-page [role=tablist]').waitFor();
  assert.equal(await page.locator('[data-operation-id]').count(),0);
  assert.equal(await page.getByRole('button',{name:'Create backup',exact:true}).count(),0);
  writeFileSync(out+'/results.json',JSON.stringify({layouts:results,workflows:['saved key required','committed response loss and immutable retry','encrypted archive download hash','reload persistence','uploaded archive verified with saved key','wrong key produces localized failure without a download','member cannot access backups']},null,2));
  console.log(`PASS ${engine}: backup workflow and ${results.filter(row=>row.engine===engine).length} layouts`);
});
