import assert from 'node:assert/strict';
import { releaseDisplayName, releaseVersion } from '../src/lib/release-name.ts';

const t = (key, params) => key === 'apps.unidentified' ? `Unidentified ${params.platform} app` : key;
const ios = {id: 'ios', name: 'Insight iOS', identifier: 'com.focusai.app.mobile', platform: 'ios'};
const android = {id: 'android', name: 'Insight Android', identifier: 'com.qualcomm.insight', platform: 'android'};
const home = {id: 'home', name: 'Insight Home Android', identifier: 'com.qualcomm.insight.consumer', platform: 'android'};
const release = {name: 'insight-native@6.0.26101301+429', apps: [ios, android]};
const original = JSON.stringify(release);
assert.equal(releaseDisplayName(release, t), 'Insight 6.0.26101301 (429)');
assert.equal(releaseDisplayName({...release, name: 'focus-ai-app@6.0.26101301+429'}, t), 'Insight 6.0.26101301 (429)');
assert.equal(releaseDisplayName({name: 'consumer@0.1.26101301+27', apps: [home]}, t), 'Insight Home 0.1.26101301 (27)');
const shared = {...release, apps: [ios, home]};
assert.equal(releaseDisplayName(shared, t), 'Insight / Insight Home 6.0.26101301 (429)');
assert.equal(releaseDisplayName(shared, t, {appId: 'home'}), 'Insight Home 6.0.26101301 (429)');
assert.equal(releaseDisplayName(shared, t, {platform: 'ios'}), 'Insight 6.0.26101301 (429)');
assert.equal(releaseDisplayName({name: 'legacy@1.2+3'}, t), '1.2 (3)');
assert.equal(releaseDisplayName({name: 'raw@1', apps: [{...ios, name: 'iOS Reader'}]}, t), 'iOS Reader 1');
assert.equal(releaseDisplayName({name: 'raw@1', apps: [{...ios, name: 'Insight Home'}]}, t), 'Insight Home 1');
assert.notEqual(releaseDisplayName(release, t), releaseDisplayName({...release, name: 'insight-native@6.0.26101301+430'}, t));
assert.equal(releaseVersion('1.0+7'), '1.0 (7)');
assert.equal(releaseVersion('pkg@1.0+sha.abc'), '1.0+sha.abc');
assert.equal(JSON.stringify(release), original, 'Display formatting must preserve transport identity');
console.log('PASS application names, historical prefixes, scoped platforms, distinct builds and untouched release keys');
