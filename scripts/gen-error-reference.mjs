// Generate docs/errors.md from the server source, and check it in CI.
//
//   node scripts/gen-error-reference.mjs            # write
//   node scripts/gen-error-reference.mjs --check    # fail if stale
//
// docs/errors/ used to hold fourteen hand-written pages describing
// `sentori.track()`, `POST /v1/track:batch`, `st_pk_` / `sk_` token
// kinds and a federation API. None of it existed; the files had not
// been touched since the initial commit, and the codes in them are
// codes this server has never sent. An error catalogue that reads as
// authoritative and is wrong costs more than none, because it is
// exactly what a reader reaches for when something has already gone
// wrong — and an agent branches on it.
//
// So it is generated. The list cannot drift from the server, because
// the server is where it comes from.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SDK = 'self-hosted/server/src/handlers/sdk';
const MW = 'core/crates/ingest-token/src';
const OUT = 'docs/errors.md';

const walk = (dir, acc = []) => {
  for (const e of readdirSync(join(ROOT, dir))) {
    const rel = `${dir}/${e}`;
    if (statSync(join(ROOT, rel)).isDirectory()) walk(rel, acc);
    else if (e.endsWith('.rs')) acc.push(rel);
  }
  return acc;
};

const codes = new Map(); // code -> Set(file)
for (const rel of walk(SDK)) {
  const src = readFileSync(join(ROOT, rel), 'utf8');
  for (const m of src.matchAll(/"error"\s*:\s*"([a-z0-9_]+)"/g)) {
    if (!codes.has(m[1])) codes.set(m[1], new Set());
    codes.get(m[1]).add(rel.split('/').pop());
  }
}
// the auth middleware sits in front of every one of them
for (const rel of walk(MW)) {
  const src = readFileSync(join(ROOT, rel), 'utf8');
  for (const m of src.matchAll(/error:\s*"([a-z0-9_]+)"/g)) {
    if (!codes.has(m[1])) codes.set(m[1], new Set());
    codes.get(m[1]).add(rel.split('/').pop());
  }
}

if (codes.size < 10) {
  console.error(
    `✗ found ${codes.size} error codes under ${SDK}. This generator is ` +
      `broken, not the tree — it will not write a catalogue it could not build.`,
  );
  process.exit(1);
}

// The hints the token middleware sends, in the order it decides them.
// Rust string literals continue across lines with a trailing `\`, so
// the pattern has to span newlines; `WrongLength` is written that way
// and was silently missing from the first generated table.
const hints = [...readFileSync(join(ROOT, MW, 'error.rs'), 'utf8').matchAll(
  /Self::(\w+)(?:\s*\{[^}]*\})?\s*=>\s*(?:\{\s*)?"((?:[^"\\]|\\[\s\S])*)"/g,
)].map(([, k, v]) => [k, v.replace(/\\\s+/g, ' ').replace(/\s+/g, ' ').trim()]);

const body = `# Error reference

<!-- GENERATED by scripts/gen-error-reference.mjs — do not edit.
     Run \`node scripts/gen-error-reference.mjs\` after changing a
     handler's error code. \`--check\` runs in preflight. -->

Every code below is one this server actually sends on a \`/v1/*\`
endpoint, extracted from the handlers rather than written by hand.
The shape is always:

\`\`\`json
{ "error": "<code>", "detail": "<free text, may be absent>" }
\`\`\`

Branch on \`error\`. \`detail\` and \`hint\` are prose for a human and
change without notice.

## Codes

| \`error\` | Sent by |
|---|---|
${[...codes.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([c, files]) => `| \`${c}\` | ${[...files].sort().join(', ')} |`)
  .join('\n')}

## 401 hints

A \`401\` always carries \`{"error":"unauthorized","hint":…}\`. The hint
names which of the checks failed, in the order they run:

| \`hint\` | Means |
|---|---|
${hints
  .filter(([k]) => k !== 'Db')
  // The hints contain backticks of their own, so they go in <code>
  // rather than in a fenced span, and `|` is escaped for the table.
  .map(([k, v]) => `| <code>${v.replace(/\|/g, '\\|')}</code> | \`${k}\` |`)
  .join('\n')}

## Not error codes

\`422\` comes from the JSON layer before any handler runs, and its body
is plain text naming the field — \`missing field \\\`occurredAt\\\`\`, for
instance. It is not one of the codes above and has no \`error\` key.
`;

const target = join(ROOT, OUT);
if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(target, 'utf8');
  } catch {
    console.error(`✗ ${OUT} is missing. Run: node scripts/gen-error-reference.mjs`);
    process.exit(1);
  }
  if (existing !== body) {
    console.error(
      `✗ ${OUT} is stale — a handler's error codes changed and the ` +
        `reference did not. Run: node scripts/gen-error-reference.mjs`,
    );
    process.exit(1);
  }
  console.log(`✓ ${OUT} matches the ${codes.size} codes in the handlers`);
} else {
  writeFileSync(target, body);
  console.log(`✓ wrote ${OUT} — ${codes.size} codes, ${hints.length} hints`);
}
